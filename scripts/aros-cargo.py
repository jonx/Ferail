"""Build Ferail with the installed native AROS Rust SDK and its exact C inputs."""
import hashlib
import json
import os
import re
from pathlib import Path
import subprocess
import sys
import tomllib


def digest(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def main():
    repo = Path(__file__).resolve().parents[1]
    project = Path(os.environ.get('AROS_PROJECT', Path.home() / 'Source/aros-project'))
    prefix = Path(os.environ.get('AROS_RUST_SDK', project / 'aros-crosstools/rust-nightly-2026-08-04-aarch64')).resolve()
    manifest = json.loads((prefix / 'aros-official-rust.json').read_text())
    native = Path(manifest['native_build'])
    result = json.loads((native / 'result.json').read_text())
    sdk, tools = Path(result['sdk']), Path(result['crosstools'])
    store = Path(os.environ.get('AROS_CRATE_STORE', project / 'crate-store')).resolve()

    def verify():
        for name, expected in manifest['installed'].items():
            if digest(prefix / name) != expected:
                raise RuntimeError('installed SDK changed: ' + name)
        for name, expected in manifest['inputs'].items():
            if digest(name) != expected:
                raise RuntimeError('SDK input changed: ' + name)
        for name, expected in result['precompiled_std'].items():
            if digest(native / 'sysroot/lib/rustlib/aarch64-unknown-aros/lib' / name) != expected:
                raise RuntimeError('precompiled std changed: ' + name)
        if digest(native / 'libaros_rs_platform.a') != result['native_adapter_archive_sha256']:
            raise RuntimeError('native platform archive changed')

    verify()
    # An independent library override would mix runtime generations.
    if os.environ.get('AROS_LINK_DIRS'):
        raise RuntimeError('AROS_LINK_DIRS is incompatible with an identified SDK; rebuild the SDK instead')
    env = os.environ.copy()
    for name in ('RUSTFLAGS', 'CARGO_BUILD_TARGET', 'RUSTC_WRAPPER', 'RUSTC_WORKSPACE_WRAPPER', 'CARGO_ENCODED_RUSTFLAGS',
                 'CARGO_TARGET_AARCH64_UNKNOWN_AROS_LINKER', 'CARGO_TARGET_AARCH64_UNKNOWN_AROS_RUSTFLAGS'):
        env.pop(name, None)
    env.update(RUSTC=str(prefix / 'bin/rustc'), RUSTDOC=str(prefix / 'bin/rustdoc'),
               CARGO_INCREMENTAL='0', AROS_SDK=str(sdk))
    patches = tomllib.loads((repo / 'packaging/aros/aros-patches.toml').read_text())['patch']['crates-io']
    lines = ['# Generated by scripts/aros-cargo.py', '[patch.crates-io]']
    for name, item in patches.items():
        if 'git' in item:
            if set(item) - {'git', 'rev', 'package'} or not re.fullmatch(r'[0-9a-f]{40}', item.get('rev', '')):
                raise RuntimeError('native git patch requires an exact revision: ' + name)
            fields = 'git = ' + json.dumps(item['git']) + ', rev = ' + json.dumps(item['rev'])
            if 'package' in item:
                fields += ', package = ' + json.dumps(item['package'])
            lines.append(name + ' = { ' + fields + ' }')
            continue
        source = Path(item['path'])
        # GPUI forks are sibling checkouts; materialized crates use the
        # selected native store, including the application-only SQLite patch.
        if name == 'gpui-pre-platform':
            source = Path(os.environ.get('AROS_GPUI_ROOT', project / 'gpui-aros')) / 'crates/gpui_platform_aros'
        elif name.startswith('gpui'):
            source = (repo / 'packaging' / source).resolve()
        else:
            source = store / source.name
        if not (source / 'Cargo.toml').is_file():
            raise RuntimeError('missing patched crate: ' + str(source) + '; build the store with crates/store.py of pomaros/rust-aros')
        fields = 'path = ' + json.dumps(str(source))
        if 'package' in item:
            fields += ', package = ' + json.dumps(item['package'])
        lines.append(name + ' = { ' + fields + ' }')
    libc = store / 'libc-0.2.190'
    if not (libc / 'Cargo.toml').is_file():
        raise RuntimeError('missing native libc: ' + str(libc))
    if '#[no_mangle]' in (libc / 'src/unix/aros/mod.rs').read_text():
        raise RuntimeError('application libc still exports replacement C providers')
    lines.append('libc = { path = ' + json.dumps(str(libc)) + ' }')
    lines += ['', '[env]', 'AROS_SDK = ' + json.dumps(str(sdk)),
              'CC_aarch64_unknown_aros = ' + json.dumps(str(tools / 'bin/clang')),
              'AR_aarch64_unknown_aros = ' + json.dumps(str(tools / 'bin/llvm-ar')),
              'CFLAGS_aarch64_unknown_aros = ' + json.dumps(
                  '--target=aarch64-unknown-aros --sysroot=' + str(sdk) +
                  ' -fno-pic -mcmodel=large -D_GNU_SOURCE -DHAVE_ENDIAN_H -Dasm=__asm__'
                  ' -DSQLITE_OMIT_WAL=1 -DSQLITE_MAX_MMAP_SIZE=0 -DSQLITE_OMIT_LOAD_EXTENSION=1'
                  ' -O2 -Wno-pointer-sign -I' + str(repo / 'packaging/aros/include-override'))]
    # pthread_sigmask and exec/types.h are supplied by the rebuilt SDK.
    generated = repo / 'target/aros'
    generated.mkdir(parents=True, exist_ok=True)
    config = generated / 'toolchain.toml'
    config.write_text('\n'.join(lines) + '\n')
    for name, value in tomllib.loads(config.read_text())['env'].items():
        env[name] = value
    # The AROS graph has its own lockfile: its patched crates resolve to
    # store paths, and writing them into the root Cargo.lock would break the
    # other platforms' builds.
    aros_lock = repo / 'packaging/aros/Cargo.lock'
    command = [str(prefix / 'bin/cargo'), '--config', str(prefix / 'cargo-config.toml'), '--config', str(config),
               '--config', 'resolver.lockfile-path=' + json.dumps(str(aros_lock))]
    lock = tomllib.loads(aros_lock.read_text())
    pins = {'libc': '0.2.190', 'memmap2': '0.9.10', 'ctor': '1.0.12',
            'inventory': '0.3.24', 'parking_lot_core': '0.9.12',
            'backtrace': '0.3.76', 'libsqlite3-sys': '0.28.0'}
    for name, version in pins.items():
        if any(p['name'] == name and p['version'] != version for p in lock['package']):
            subprocess.run(command + ['update', '-p', name, '--precise', version], cwd=repo, env=env, check=True)
    if any(p['name'] == 'getrandom' and p['version'] == '0.4.2' for p in lock['package']):
        subprocess.run(command + ['update', '-p', 'getrandom@0.4.2', '--precise', '0.4.3'],
                       cwd=repo, env=env, check=True)
    completed = subprocess.run(command + sys.argv[1:], cwd=repo, env=env)
    verify()
    return completed.returncode


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (OSError, KeyError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print('aros-cargo: ' + str(error), file=sys.stderr)
        raise SystemExit(2)
